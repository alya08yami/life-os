import {test,expect} from '@playwright/test';
test.afterEach(async({page})=>{expect(await page.pageErrors()).toEqual([]);});
test('recipe quantities, cooking notes and scaled shopping survive editing and reload',async({page})=>{
  await page.goto('http://127.0.0.1:8081/inbox?kind=recipe');
  await page.getByTestId('capture-text').fill('Carrot soup');
  await page.getByRole('textbox',{name:'Ингредиенты · по одному на строку',exact:true}).fill('Carrot\nSalt');
  await page.getByRole('textbox',{name:'Количество: Carrot',exact:true}).fill('100');
  await page.getByRole('textbox',{name:'Единица: Carrot',exact:true}).fill('g');
  await page.getByRole('textbox',{name:'Шаги · по одному на строку',exact:true}).fill('Boil\nBlend');
  await page.getByRole('textbox',{name:'Порции',exact:true}).fill('2');
  await page.getByRole('textbox',{name:'Время приготовления · мин',exact:true}).fill('25');
  await page.getByRole('textbox',{name:'Заметки к рецепту',exact:true}).fill('Serve warm');
  await page.getByTestId('save-item').click();await page.getByRole('button',{name:'Carrot soup',exact:true}).click();
  await page.getByRole('button',{name:'Подтвердить',exact:true}).click();
  await expect(page.getByText('Время приготовления: 25 мин',{exact:true})).toBeVisible();
  await page.getByRole('radio',{name:'Ингредиенты',exact:true}).click();
  await page.getByRole('textbox',{name:'Порции',exact:true}).fill('4');
  await expect(page.getByText('○ Carrot — 200 g',{exact:true})).toBeVisible();
  await expect(page.getByText('○ Salt',{exact:true})).toBeVisible();
  await page.getByRole('textbox',{name:'Порции',exact:true}).fill('0');
  await expect(page.getByRole('button',{name:'Добавить ингредиенты в покупки',exact:true})).toBeDisabled();
  await page.getByRole('textbox',{name:'Порции',exact:true}).fill('4');
  await page.getByRole('button',{name:'Добавить ингредиенты в покупки',exact:true}).click();
  await expect(page.getByRole('textbox',{name:'Количество: Carrot',exact:true})).toHaveValue('200');
  await page.getByRole('textbox',{name:'Количество: Carrot',exact:true}).fill('175');
  await page.getByRole('checkbox',{name:'Salt',exact:true}).click();
  await page.getByRole('button',{name:'Добавить выбранное',exact:true}).click();
  await expect(page.getByText('Добавлено в покупки',{exact:true})).toBeVisible();
  const detail=page.url();await page.reload();
  await expect(page.getByRole('textbox',{name:'Порции',exact:true})).toHaveValue('2');
  await page.getByRole('radio',{name:'Заметки',exact:true}).click();await expect(page.getByText('Serve warm',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Редактировать',exact:true}).click();
  await expect(page.getByRole('textbox',{name:'Количество: Carrot',exact:true})).toHaveValue('100');
  await page.getByRole('textbox',{name:'Заметки к рецепту',exact:true}).fill('Serve warm with bread');
  await page.getByRole('button',{name:'Сохранить изменения',exact:true}).click();
  await expect(page.getByRole('button',{name:'Редактировать',exact:true})).toBeVisible();
  await page.getByRole('radio',{name:'Ингредиенты',exact:true}).click();
  await expect(page.getByText('○ Carrot — 100 g',{exact:true})).toBeVisible();
  await page.screenshot({path:'docs/screenshots/recipe-quantities.png',fullPage:true});
  await page.getByRole('button',{name:'Добавить ингредиенты в покупки',exact:true}).click();
  await page.getByRole('checkbox',{name:'Salt',exact:true}).click();
  await page.getByRole('button',{name:'Добавить выбранное',exact:true}).click();await expect(page.getByText('Добавлено в покупки',{exact:true})).toBeVisible();
  await page.goto('http://127.0.0.1:8081/tasks');
  await expect(page.getByRole('button',{name:'Carrot — 175 g',exact:true})).toHaveCount(1);
  await expect(page.getByRole('button',{name:'Salt',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Carrot — 175 g',exact:true}).click();await page.getByRole('button',{name:'Исходный рецепт',exact:true}).click();await expect(page).toHaveURL(detail);
  await page.goto('http://127.0.0.1:8081/section/food');await expect(page.getByText('25 мин',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'В избранное: Carrot soup',exact:true}).click();
  await expect(page.getByRole('button',{name:'Убрать из избранного: Carrot soup',exact:true})).toBeVisible();
  await page.reload();await expect(page.getByRole('button',{name:'Убрать из избранного: Carrot soup',exact:true})).toBeVisible();
});
