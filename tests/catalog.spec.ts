test('personal contextual add and favorite persist without repeated category questions',async({page})=>{
  await page.goto('http://127.0.0.1:8081/wishlist');
  await page.getByRole('button',{name:'Добавить',exact:true}).click();
  await page.getByRole('button',{name:'Ввести вручную',exact:true}).click();
  await page.getByRole('textbox',{name:'Название',exact:true}).fill('My own perfume');
  await expect(page.getByText('Тип карточки',{exact:true})).toHaveCount(0);
  await page.getByRole('textbox',{name:'Бренд',exact:true}).fill('My brand');
  await page.getByRole('textbox',{name:'Цена',exact:true}).fill('2500');
  await page.getByRole('button',{name:'Добавить товар',exact:true}).click();
  await expect(page).toHaveURL(/\/product\//);
  await expect(page.getByRole('heading',{name:'My own perfume',exact:true})).toBeVisible();
  await expect(page.getByText('Указано вручную',{exact:true}).filter({visible:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'В избранное: My own perfume',exact:true}).click();
  await expect(page.getByRole('button',{name:'Убрать из избранного: My own perfume',exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button',{name:'Убрать из избранного: My own perfume',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Назад',exact:true}).click();
  await expect(page.getByRole('radio',{name:'Мои',exact:true})).toBeChecked();
  await expect(page.getByRole('button',{name:'My own perfume',exact:true})).toBeVisible();
  await page.screenshot({path:'docs/screenshots/wishlist-personal.png',fullPage:true});
  await page.getByRole('button',{name:'My own perfume',exact:true}).click();
  await page.getByRole('button',{name:'Редактировать',exact:true}).click();
  await page.getByRole('textbox',{name:'Название',exact:true}).fill('Revised perfume');
  await page.getByRole('textbox',{name:'Цена',exact:true}).fill('12.50');
  await page.getByRole('button',{name:'Сохранить изменения',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Revised perfume',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Удалить',exact:true}).click();
  await page.getByRole('button',{name:'Удалить',exact:true}).click();
  await expect(page).toHaveURL(/\/wishlist$/);
  await expect(page.getByRole('button',{name:'Revised perfume',exact:true})).toHaveCount(0);
});
test('recipe connects only selected ingredients to purchases and keeps source links',async({page})=>{
  await page.goto('http://127.0.0.1:8081/inbox?kind=recipe');
  await page.getByTestId('capture-text').fill('Connected soup');
  await page.getByRole('textbox',{name:'Ингредиенты · по одному на строку',exact:true}).fill('Water\nCarrot\nSalt');
  await page.getByRole('textbox',{name:'Шаги · по одному на строку',exact:true}).fill('Boil');
  await page.getByTestId('save-item').click();
  await page.getByRole('button',{name:'Connected soup',exact:true}).click();
  await page.getByRole('button',{name:'Подтвердить',exact:true}).click();
  await page.getByRole('button',{name:'Добавить ингредиенты в покупки',exact:true}).click();
  await page.getByRole('checkbox',{name:'Water',exact:true}).click();
  await page.getByRole('button',{name:'Добавить выбранное',exact:true}).click();
  await expect(page.getByText('Добавлено в покупки',{exact:true})).toBeVisible();
  await page.goto('http://127.0.0.1:8081/section/tasks');
  await expect(page.getByRole('button',{name:'Carrot',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Water',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Carrot',exact:true}).click();
  await page.getByRole('button',{name:'Исходный рецепт',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Connected soup',exact:true})).toBeVisible();
});
test('hidden home sections persist and can be re-enabled',async({page})=>{
  await page.goto('http://127.0.0.1:8081/settings');
  await page.getByRole('checkbox',{name:'Гардероб',exact:true}).click();
  await expect(page.getByRole('checkbox',{name:'Гардероб',exact:true})).not.toBeChecked();
  await page.goto('http://127.0.0.1:8081');
  await expect(page.getByRole('button',{name:'Гардероб',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Мои дела',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Входящие',exact:true})).toBeVisible();
});
