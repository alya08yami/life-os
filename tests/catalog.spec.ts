import {test,expect} from '@playwright/test';
test.afterEach(async({page})=>{expect(await page.pageErrors()).toEqual([]);});
test('dashboard is a two-column category catalog at mobile and desktop widths',async({page})=>{
  await page.goto('http://127.0.0.1:8081');
  for(const width of [360,1280]){
    await page.setViewportSize({width,height:950});
    const wishes=page.getByRole('button',{name:'Хотелки',exact:true}),home=page.getByRole('button',{name:'Дом',exact:true});
    await expect(wishes).toBeVisible();const a=await wishes.boundingBox(),b=await home.boundingBox();
    expect(a).not.toBeNull();expect(b).not.toBeNull();expect(Math.abs(a!.y-b!.y)).toBeLessThan(2);expect(b!.x).toBeGreaterThan(a!.x+a!.width-1);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    await page.screenshot({path:`docs/screenshots/catalog-${width}.png`,fullPage:true});
  }
  await page.getByRole('tab',{name:'Профиль',exact:true}).click();
  await page.getByRole('button',{name:'Настройки',exact:true}).click();
  await expect(page.getByText('Язык',{exact:true})).toBeVisible();
});
